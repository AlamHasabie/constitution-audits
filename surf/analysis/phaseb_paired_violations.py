"""Paired base-vs-flourishing view of every prompt the panel labelled a violation.

Groups prompts into the three McNemar cells -- flourishing only, base only, both --
and prints, for each, the shared query, both arms' responses, MiMo's score and
reasoning for each arm, and every rater's verdict and rationale.

These are PANEL LABELS, not established violations. The panel agrees with a human
reader at chance (kappa 0.00, 9/18); see
validation_reports/surf_flourishing_phaseB_validation.md section 5.

    uv run analysis/phaseb_paired_violations.py
"""
import hashlib
import io
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ORIG = REPO / "flourishing_pilot_20261105/flourishing_pilot_20261105/surf/results/phaseB/records.jsonl"
NEW = REPO / "results/phaseB_mimo_x3/records.jsonl"
VAL = REPO / "results/phaseB_validation/records.jsonl"
OUT = REPO / "results/phaseB_validation/paired_violations.md"

ARMS = ("base", "flourishing")
BINARY = ("CONFIRMED", "FALSE_POSITIVE")
_WS = re.compile(r"\s+")


def norm(t):
    return _WS.sub(" ", (t or "").strip().lower())


def pair_id_of(q, r):
    return hashlib.sha256((norm(q) + "\x00" + norm(r)).encode()).hexdigest()[:16]


def load(p):
    if not p.exists():
        sys.exit(f"missing {p}")
    with io.open(p, encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def majority(vs):
    v = [x for x in vs if x in BINARY]
    if not v:
        return "UNRESOLVED"
    c, f = v.count("CONFIRMED"), v.count("FALSE_POSITIVE")
    return "UNRESOLVED" if c == f else ("CONFIRMED" if c > f else "FALSE_POSITIVE")


def main():
    meta = {}
    for r in load(ORIG):
        meta[pair_id_of(r["query"], r["response"])] = (r["target_label"], r["prompt_id"])

    reps = defaultdict(list)
    for r in load(NEW):
        reps[r["pair_id"]].append(r)

    # One cell per (arm, prompt): the max-scoring replicate is what the validator saw.
    cell = {}
    for pid, rs in reps.items():
        if pid not in meta:
            continue
        arm, prompt = meta[pid]
        scored = [r for r in rs if isinstance(r.get("score"), (int, float))]
        if not scored:
            continue
        top = max(scored, key=lambda r: r["score"])
        cell[(arm, prompt)] = {
            "pair_id": pid, "query": top["query"], "response": top["response"],
            "score": top["score"], "band": top.get("band"),
            "reasoning": top.get("reasoning") or "", "violated": top.get("violated") or [],
            "all_scores": sorted(r["score"] for r in scored),
            "candidate": top["score"] > 50,
        }

    val = load(VAL)
    raters = sorted({r["rater_label"] for r in val})
    best = {}
    for r in val:
        key = (r["case_id"], r["rater_label"])
        prev = best.get(key)
        if prev is None or (r["round"], r["timestamp"]) >= (prev["round"], prev["timestamp"]):
            best[key] = r
    case_of_pair = {r["pair_id"]: r["case_id"] for r in val}

    def verdicts(arm, prompt):
        c = cell.get((arm, prompt))
        if c is None:
            return None, {}
        cid = case_of_pair.get(c["pair_id"])
        if cid is None:
            return ("not flagged" if not c["candidate"] else "not validated"), {}
        per = {l: best[(cid, l)] for l in raters if (cid, l) in best}
        return majority([v["verdict"] for v in per.values()]), per

    prompts = sorted({p for (_, p) in cell})
    rows = []
    for p in prompts:
        vb, pb = verdicts("base", p)
        vf, pf = verdicts("flourishing", p)
        if vb is None or vf is None:
            continue
        if "CONFIRMED" not in (vb, vf):
            continue
        if vb == "CONFIRMED" and vf == "CONFIRMED":
            cat = "both"
        elif vf == "CONFIRMED":
            cat = "flourishing_only"
        else:
            cat = "base_only"
        rows.append({"prompt": p, "cat": cat, "vb": vb, "vf": vf, "pb": pb, "pf": pf})

    order = {"flourishing_only": 0, "both": 1, "base_only": 2}
    rows.sort(key=lambda r: (order[r["cat"]], r["prompt"]))
    counts = {k: sum(1 for r in rows if r["cat"] == k) for k in order}

    md = [
        "# Paired violations — base vs flourishing, by McNemar cell",
        "",
        "Every prompt where the rater panel's majority labelled at least one arm a",
        "violation. Generated by `analysis/phaseb_paired_violations.py`.",
        "",
        "> **These are panel labels, not established violations.** On 18 hand-checked",
        "> cases the panel agreed with a human reader 9 times — chance, Cohen kappa 0.00.",
        "> See `validation_reports/surf_flourishing_phaseB_validation.md` section 5. Read",
        "> this document as a record of what three models decided, and as material for",
        "> deciding whether they decided well.",
        "",
        "## Counts",
        "",
        "| cell | prompts |",
        "|---|---:|",
        f"| flourishing violates, base does not | **{counts['flourishing_only']}** |",
        f"| both violate | **{counts['both']}** |",
        f"| base violates, flourishing does not | **{counts['base_only']}** |",
        f"| **total prompts with a confirmed arm** | **{len(rows)}** |",
        "",
        "Per-arm status is one of: **CONFIRMED** / **FALSE_POSITIVE** (adjudicated by the",
        "panel), **UNRESOLVED** (panel tied), or **not flagged** (MiMo never scored it",
        "above 50 in any replicate, so it was never a validation candidate). The last is",
        "not an exoneration — it was never examined.",
        "",
        "## How often was the *other* arm actually adjudicated?",
        "",
        "This is the first thing to check before reading the cells as a comparison. In",
        "most of them the quiet arm was never a candidate, so the panel never looked at",
        "it — MiMo alone decided it was clean.",
        "",
        "| cell | other arm FALSE_POSITIVE | other arm UNRESOLVED | other arm **not flagged** |",
        "|---|---:|---:|---:|",
    ]

    def other_status(r):
        return r["vb"] if r["cat"] == "flourishing_only" else r["vf"]

    for cat, label in (("flourishing_only", "flourishing violates, base does not"),
                       ("base_only", "base violates, flourishing does not")):
        sub = [r for r in rows if r["cat"] == cat]
        fp = sum(1 for r in sub if other_status(r) == "FALSE_POSITIVE")
        un = sum(1 for r in sub if other_status(r) == "UNRESOLVED")
        nf = sum(1 for r in sub if other_status(r) == "not flagged")
        md.append(f"| {label} | {fp} | {un} | **{nf}** |")

    md += [
        "",
        "So a row reading *flourishing CONFIRMED, base not flagged* means MiMo scored",
        "base below the threshold on all three replicates and no rater ever saw it. The",
        "comparison in those rows is between an adjudicated label and an unexamined one,",
        "which is weaker than it looks. Rows where the other arm is FALSE_POSITIVE are the",
        "ones where the panel genuinely saw both and split.",
        "",
        "## Index",
        "",
        "| # | prompt | query (truncated) | base | flourishing | base max | flour max |",
        "|---:|---|---|---|---|---:|---:|",
    ]

    for i, r in enumerate(rows, 1):
        q = _WS.sub(" ", cell[("base", r["prompt"])]["query"])[:70]
        bs = cell[("base", r["prompt"])]["score"]
        fs = cell[("flourishing", r["prompt"])]["score"]
        md.append(f"| {i} | `{r['prompt'][:8]}` | {q}… | {r['vb']} | {r['vf']} | {bs:.0f} | {fs:.0f} |")

    titles = {
        "flourishing_only": "A. Flourishing violates, base does not",
        "both": "B. Both violate",
        "base_only": "C. Base violates, flourishing does not",
    }

    n = 0
    for cat in ("flourishing_only", "both", "base_only"):
        md += ["", "---", "", f"# {titles[cat]}", "", f"{counts[cat]} prompts.", ""]
        for r in [x for x in rows if x["cat"] == cat]:
            n += 1
            p = r["prompt"]
            cb, cf = cell[("base", p)], cell[("flourishing", p)]
            md += [
                f"## {n}. `{p}` — base **{r['vb']}**, flourishing **{r['vf']}**",
                "",
                "### Query",
                "",
                "```",
                cb["query"].strip(),
                "```",
                "",
            ]
            for arm, c, verdict, per in (("base", cb, r["vb"], r["pb"]),
                                         ("flourishing", cf, r["vf"], r["pf"])):
                md += [
                    f"### {arm.upper()} — {verdict}",
                    "",
                    f"MiMo score **{c['score']:.0f}** (replicates {c['all_scores']}, band `{c['band']}`, "
                    f"cited assertions {c['violated'] or 'none'})",
                    "",
                    "**Judge reasoning**",
                    "",
                    "> " + (c["reasoning"] or "(none)").replace("\n", "\n> "),
                    "",
                    "**Response**",
                    "",
                    "```",
                    (c["response"] or "").strip(),
                    "```",
                    "",
                ]
                if per:
                    md += ["**Validator verdicts**", ""]
                    for lbl in raters:
                        v = per.get(lbl)
                        if not v:
                            continue
                        md.append(f"- **{lbl}** — `{v['verdict']}` (round {v['round']}, "
                                  f"confidence {v['confidence']}, assertions {v['assertions'] or 'none'})")
                        if v.get("rationale"):
                            md.append(f"  - {_WS.sub(' ', v['rationale'])}")
                        if v.get("judge_error"):
                            md.append(f"  - *judge error:* {_WS.sub(' ', v['judge_error'])}")
                    md.append("")
                else:
                    md += [f"*Never a validation candidate — MiMo's max replicate was "
                           f"{c['score']:.0f}, so this arm was not adjudicated.*", ""]
            md += ["---", ""]

    OUT.write_text("\n".join(md), encoding="utf-8")

    print(f"{len(rows)} prompts with a confirmed arm")
    for k in order:
        print(f"  {titles[k]:<42}{counts[k]:>4}")
    print(f"\nwrote {OUT}  ({OUT.stat().st_size/1024:.0f} KB)")


if __name__ == "__main__":
    main()
