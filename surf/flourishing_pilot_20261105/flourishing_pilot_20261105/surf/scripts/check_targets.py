"""
Smoke-check every model the Flourishing pilot needs, through SURF's own layer.

Deliberately uses surf.core.models.ModelResource rather than raw HTTP, so what
gets validated is the exact path Phase A will take: the provider string parsing
in parse_model_string, and the API-key resolution in _get_default_api_key -- the
place where a URL-style provider silently falls back to MODEL_API_KEY and
defaults to the literal "dummy".

Checks three roles, because each fails differently and each failure is quiet:

  target     a dead arm means that model contributes nothing to the comparison
  judge      an auth failure writes reward_score=null, which is NOT a zero
  generator  a parse failure drops candidates into the failures file, so the
             run just quietly produces fewer candidates than you asked for

Usage:
    uv run scripts/check_targets.py
    uv run scripts/check_targets.py --port 8001
    uv run scripts/check_targets.py --skip-judge --skip-generator
"""

import argparse
import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from surf.core.models import ModelResource, parse_model_string  # noqa: E402

BASE_ID = "google/gemma-3-4b-it"

DEFAULT_JUDGE = (
    "https://api.deepinfra.com/v1/openai:XiaomiMiMo/MiMo-V2.6-Flash"
)
DEFAULT_GENERATOR = "openrouter:meta-llama/llama-3.1-70b-instruct"

# Short, harmless, and answerable by any instruction-tuned model.
PROBE = "Reply with exactly the word: ok"

# The generator is checked on the real contract instead: its output has to carry
# a <query_1> tag, because loop.py builds it with stop=["</query_1>"] and
# max_tokens=512, and _generate_query returns None when the tag never arrives.
GENERATOR_PROBE = (
    "This is a description of a query submitted to a large language model "
    "assistant:\n- The user asks for feedback on a business plan.\n\n"
    "Your task is as follows. Please output five queries, in order of most to "
    "least likely to be generated by the description. Output the queries in xml "
    "tags of the form <query_1></query_1> <query_2></query_2> <query_3></query_3> "
    "<query_4></query_4> <query_5></query_5>. Do not output any other text."
)


async def probe(label: str, model_str: str, prompt: str, *,
                max_tokens: int = 32, stop: list[str] | None = None) -> dict:
    """Call one model once and report what came back."""
    result = {"label": label, "model": model_str, "ok": False, "detail": ""}

    try:
        parsed = parse_model_string(model_str)
    except Exception as e:  # noqa: BLE001
        result["detail"] = f"unparseable model string: {e}"
        return result

    result["provider"] = parsed.provider
    if parsed.api_key in (None, "", "dummy"):
        # Not fatal: a local vLLM ignores the key. Worth saying for a remote one.
        result["key"] = "unset/dummy"
    else:
        result["key"] = "set"

    model = ModelResource.from_string(
        model_str, max_concurrency=1, max_tokens=max_tokens,
        temperature=1.0, stop=stop,
    )
    try:
        response = await model.call(prompt)
        if not response or not response.strip():
            result["detail"] = "empty response"
            return result
        result["ok"] = True
        result["detail"] = response.strip().replace("\n", " ")[:80]
    except Exception as e:  # noqa: BLE001 - reporting, not control flow
        result["detail"] = f"{type(e).__name__}: {e}"[:200]
    finally:
        try:
            await model.shutdown()
        except Exception:  # noqa: BLE001
            pass

    return result


async def main() -> int:
    parser = argparse.ArgumentParser(
        description="Smoke-check the pilot's targets, judge and generator"
    )
    parser.add_argument("--port", type=int, default=8000,
                        help="Port the vLLM server is on (default 8000)")
    parser.add_argument("--host", default="localhost")
    parser.add_argument("--base", default=BASE_ID,
                        help=f"Base model id as vLLM serves it (default {BASE_ID})")
    parser.add_argument("--personas", nargs="+", default=["goodness", "sycophancy"],
                        help="LoRA module names as vLLM serves them")
    parser.add_argument("--judge", default=DEFAULT_JUDGE)
    parser.add_argument("--generator", default=DEFAULT_GENERATOR)
    parser.add_argument("--skip-targets", action="store_true")
    parser.add_argument("--skip-judge", action="store_true")
    parser.add_argument("--skip-generator", action="store_true")
    args = parser.parse_args()

    from dotenv import load_dotenv
    load_dotenv()

    endpoint = f"http://{args.host}:{args.port}/v1"
    checks = []

    if not args.skip_targets:
        checks.append(("target  base", f"{endpoint}:{args.base}", PROBE, 32, None))
        for p in args.personas:
            label = "flourishing" if p == "goodness" else p
            checks.append((f"target  {label}", f"{endpoint}:{p}", PROBE, 32, None))

    if not args.skip_judge:
        checks.append(("judge", args.judge, PROBE, 32, None))

    if not args.skip_generator:
        checks.append(("generator", args.generator, GENERATOR_PROBE, 512,
                       ["</query_1>"]))

    print("Checking the pilot's models through surf.core.models\n")

    results = []
    for label, model_str, prompt, max_tokens, stop in checks:
        print(f"  {label:22s} ...", end="", flush=True)
        r = await probe(label, model_str, prompt, max_tokens=max_tokens, stop=stop)

        # The generator's contract is the tag, not a successful HTTP call.
        if r["ok"] and label == "generator":
            if "<query_1" not in r["detail"] and "query_1" not in r["detail"]:
                r["ok"] = False
                r["detail"] = ("no <query_1> tag in output -- _generate_query "
                               "would return None and drop the candidate. "
                               f"Got: {r['detail'][:60]}")

        print(" ok" if r["ok"] else " FAIL")
        results.append(r)

    print()
    width = max(len(r["label"]) for r in results)
    for r in results:
        mark = "ok  " if r["ok"] else "FAIL"
        print(f"  [{mark}] {r['label']:{width}s}  {r['model']}")
        print(f"         {' ' * width}  key={r.get('key', '?')}  {r['detail']}")
    print()

    failed = [r for r in results if not r["ok"]]
    if not failed:
        print("All checks passed. Phase A command:")
        print()
        print(f"  uv run run_persona.py --persona flourishing \\")
        print(f"      --rubric rubrics/flourishing_banded.yaml \\")
        print(f"      --target {endpoint}:{args.base} \\")
        print(f"      --iterations 5 --candidates 15 --buffer-size 10")
        print()
        print("Repeat per arm, varying only --target. Judge, generator, attribute")
        print("set and seeds stay fixed across the three runs.")
        return 0

    print(f"{len(failed)} check(s) failed:")
    for r in failed:
        print(f"  {r['label']}: {r['detail']}")
    print()
    print("A target or judge that fails here fails silently in a real run --")
    print("unscored candidates get reward_score=null, which is not a zero.")
    return 1


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
